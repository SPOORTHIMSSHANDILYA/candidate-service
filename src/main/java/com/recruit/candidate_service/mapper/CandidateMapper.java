package com.recruit.candidate_service.mapper;

import com.recruit.candidate_service.entities.Candidate;
import com.recruit.candidate_service.models.CandidateRequest;
import com.recruit.candidate_service.models.CandidateResponse;
import com.recruit.candidate_service.models.CandidateSummary;
import org.mapstruct.*;

@Mapper(componentModel = "spring", unmappedTargetPolicy = ReportingPolicy.ERROR)
public interface CandidateMapper {

    @Mapping(target = "candidateCode", source = "id", qualifiedByName = "candidateCode")
    CandidateSummary toSummary(Candidate candidate);

    @Mapping(target = "candidateCode", source = "id", qualifiedByName = "candidateCode")
    CandidateResponse toResponse(Candidate candidate);

    //request -> NEW entity (POST)

    @Mapping(target = "id",        ignore = true)   // generated by Hibernate
    @Mapping(target = "version",   ignore = true)   // managed by @Version
    @Mapping(target = "createdAt", ignore = true)   // set by @CreationTimestamp
    @Mapping(target = "candidateStatus", ignore = true) //defaults to true
    @Mapping(target = "updatedAt", ignore = true)   // set by @UpdateTimestamp
    @Mapping(target = "createdBy", ignore = true)   // set by the service
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "skills",    ignore = true)   // service cleans them, then replaceSkills()
    Candidate toEntity(CandidateRequest request);

    // request -> EXISTING entity (PUT)

    @Mapping(target = "id",        ignore = true)
    @Mapping(target = "version",   ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "candidateStatus", ignore = true)
    @Mapping(target = "createdBy", ignore = true)
    @Mapping(target = "updatedBy", ignore = true)
    @Mapping(target = "skills",    ignore = true)
    void updateEntity(CandidateRequest request, @MappingTarget Candidate candidate);

    @Named("candidateCode")
    default String toCandidateCode(Long id) {
        return id == null ? null : String.format("CAN-%05d", id);
    }
}